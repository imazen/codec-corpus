//! `R2Corpus`: anonymous, path-keyed corpus sync from a public HTTP(S)
//! bucket (Cloudflare R2 with public read, or anything that serves plain
//! GETs) — see imazen/codec-corpus#2.
//!
//! [`Corpus`](crate::Corpus) serves curated, versioned datasets from GitHub
//! release tarballs. `R2Corpus` targets *continuously-growing* corpora (fuzz
//! seeds, CI-generated fixtures) that are too large or too churny for
//! releases but still need an anonymous, cross-platform fetch.
//!
//! ## Storage layout
//!
//! For a prefix `fuzz/zentiff/fuzz_decode/` the bucket holds:
//!
//! ```text
//! <base>/fuzz/zentiff/fuzz_decode.list           auto-generated JSON index
//! <base>/fuzz/zentiff/fuzz_decode.tar.zst        optional frozen bundle
//! <base>/fuzz/zentiff/fuzz_decode/<rel-path>     individual objects
//! ```
//!
//! The `.list` is a [`ListIndex`]: `{ path: { size, sha256, in_bundle } }`
//! plus an optional [`BundleInfo`]. It is generated by a push tool
//! ([`ListIndex::from_dir`]), never hand-edited.
//!
//! ## Pull algorithm
//!
//! 1. Fetch the `.list` (one small request). If that fails but a previous
//!    pull left a cached list, the cached corpus is used as-is.
//! 2. Diff against the local cache by size + SHA-256.
//! 3. If a bundle exists and enough of its files are missing (default: 40 %),
//!    download it once and extract with the system `tar`.
//! 4. Fetch whatever is still missing as individual objects, several at a
//!    time ([`PullOptions::parallelism`]); every file is verified against its
//!    listed SHA-256 before it lands in place.
//! 5. Files in the cache dir that are no longer listed are removed, so the
//!    directory mirrors the remote prefix.
//! 6. If the `.list` names child prefixes ([`ListIndex::children`]), each
//!    child is pulled the same way into a sub-directory, so
//!    `pull("fuzz/zentiff/")` fetches every leaf under it and `pull("fuzz/")`
//!    fetches everything. The returned [`R2Corpus::list`] is the merged view
//!    (child files keyed `child/rel`).
//!
//! Downloads shell out to `curl`/`wget`/`powershell` like the rest of the
//! crate; nothing is compiled in. On `wasm32` only [`PullMode::Offline`] works
//! (it reads a cache populated on the host).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::sync::Mutex;
use std::sync::atomic::{AtomicU64, Ordering};

use serde::{Deserialize, Serialize};

use crate::Error;
use crate::sha256;

/// Default public base URL for the imazen `codec-corpus` R2 bucket.
pub const DEFAULT_R2_BASE_URL: &str = "https://codec-corpus.r2.imazen.org";

/// Name of the cached copy of the remote `.list` inside a pulled prefix dir.
const CACHED_LIST_NAME: &str = ".list.json";

/// Current `.list` schema version.
pub const LIST_VERSION: u32 = 1;

// ---------------------------------------------------------------------------
// .list schema
// ---------------------------------------------------------------------------

/// One file in a [`ListIndex`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FileEntry {
    /// Size in bytes.
    pub size: u64,
    /// Lowercase hex SHA-256 of the contents.
    pub sha256: String,
    /// Whether the file is also contained in the prefix's bundle.
    #[serde(default)]
    pub in_bundle: bool,
}

/// The optional frozen `.tar` / `.tar.gz` / `.tar.zst` snapshot of a prefix.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BundleInfo {
    /// Object key relative to the base URL, e.g. `fuzz/zentiff/fuzz_decode.tar.zst`.
    pub key: String,
    /// Size of the archive in bytes.
    pub size: u64,
    /// Lowercase hex SHA-256 of the archive.
    pub sha256: String,
    /// Number of files inside the archive.
    pub file_count: u64,
    /// Sum of the member file sizes.
    pub uncompressed_size: u64,
}

/// The auto-generated `<prefix>.list` index of one corpus prefix.
///
/// Paths are relative to the prefix, forward-slash separated, and never
/// contain `..` or absolute components (pull rejects such lists).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ListIndex {
    /// Schema version ([`LIST_VERSION`]).
    pub version: u32,
    /// The prefix this index describes, with a trailing `/`.
    pub prefix: String,
    /// RFC 3339 timestamp of generation (informational).
    pub generated_at: String,
    /// The frozen bundle, if one has been published for this prefix.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub bundle: Option<BundleInfo>,
    /// Every file under the prefix, keyed by relative path.
    pub files: BTreeMap<String, FileEntry>,
    /// Child prefixes (single path components, no `/`) that have their own
    /// `.list`. `pull` recurses into them; a push registers its leaf here.
    /// A node may have both `files` and `children`, but no file may live
    /// under a child's name.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub children: Vec<String>,
}

impl ListIndex {
    /// Parse a `.list` document.
    pub fn parse(json: &str) -> Result<Self, Error> {
        let list: ListIndex =
            serde_json::from_str(json).map_err(|e| Error::ListParse(e.to_string()))?;
        if list.version != LIST_VERSION {
            return Err(Error::ListParse(format!(
                "unsupported .list version {} (this crate speaks {LIST_VERSION})",
                list.version
            )));
        }
        list.validate()?;
        Ok(list)
    }

    /// Check every file path and child name for safety and mutual
    /// consistency (what [`ListIndex::parse`] enforces on input and a push
    /// enforces on output).
    pub fn validate(&self) -> Result<(), Error> {
        for path in self.files.keys() {
            validate_rel_path(path)?;
        }
        let mut seen = std::collections::BTreeSet::new();
        for child in &self.children {
            validate_rel_path(child)?;
            if child.contains('/') {
                return Err(Error::ListParse(format!(
                    "child prefix '{child}' must be a single path component"
                )));
            }
            if !seen.insert(child.as_str()) {
                return Err(Error::ListParse(format!(
                    "duplicate child prefix '{child}'"
                )));
            }
            let under = format!("{child}/");
            if self
                .files
                .keys()
                .any(|f| f == child || f.starts_with(&under))
            {
                return Err(Error::ListParse(format!(
                    "file entries collide with child prefix '{child}'"
                )));
            }
        }
        Ok(())
    }

    /// Register `child` as a sub-prefix of this node (idempotent, keeps the
    /// list sorted). Fails if the name is unsafe or collides with a file.
    pub fn add_child(&mut self, child: &str) -> Result<(), Error> {
        let child = child.trim_matches('/');
        if !self.children.iter().any(|c| c == child) {
            self.children.push(child.to_string());
            self.children.sort();
        }
        if let Err(e) = self.validate() {
            self.children.retain(|c| c != child);
            return Err(e);
        }
        Ok(())
    }

    /// Serialize to pretty JSON.
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("ListIndex is always serializable")
    }

    /// Build an index by walking `dir`: every regular file becomes an entry
    /// keyed by its `/`-separated path relative to `dir`, with size and
    /// SHA-256. No bundle is recorded (`in_bundle: false` everywhere).
    ///
    /// This is the push side's half of the format: upload the files under
    /// `prefix` and this document as `<prefix-without-trailing-slash>.list`.
    pub fn from_dir(dir: &Path, prefix: &str) -> Result<Self, Error> {
        let prefix = normalize_prefix(prefix)?;
        let mut files = BTreeMap::new();
        let mut stack = vec![dir.to_path_buf()];
        while let Some(d) = stack.pop() {
            let mut entries: Vec<_> = std::fs::read_dir(&d)?.collect::<Result<_, _>>()?;
            entries.sort_by_key(|e| e.file_name());
            for entry in entries {
                let path = entry.path();
                let name = entry.file_name();
                let name = name.to_string_lossy();
                if name.starts_with('.') {
                    continue; // .list.json, .lock, .tmp-*, editor droppings
                }
                if path.is_dir() {
                    stack.push(path);
                } else if path.is_file() {
                    let rel = path
                        .strip_prefix(dir)
                        .map_err(|e| std::io::Error::other(e.to_string()))?;
                    let rel = rel
                        .components()
                        .map(|c| c.as_os_str().to_string_lossy().into_owned())
                        .collect::<Vec<_>>()
                        .join("/");
                    let size = std::fs::metadata(&path)?.len();
                    let sha = sha256::sha256_file(&path)?;
                    files.insert(
                        rel,
                        FileEntry {
                            size,
                            sha256: sha,
                            in_bundle: false,
                        },
                    );
                }
            }
        }
        Ok(Self {
            version: LIST_VERSION,
            prefix,
            generated_at: rfc3339_now(),
            bundle: None,
            files,
            children: Vec::new(),
        })
    }

    /// An empty node list for `prefix` (no files, no bundle) — the shape a
    /// directory-only prefix such as `fuzz/` has before children are added.
    pub fn empty(prefix: &str) -> Result<Self, Error> {
        Ok(Self {
            version: LIST_VERSION,
            prefix: normalize_prefix(prefix)?,
            generated_at: rfc3339_now(),
            bundle: None,
            files: BTreeMap::new(),
            children: Vec::new(),
        })
    }

    /// Number of files listed.
    pub fn len(&self) -> usize {
        self.files.len()
    }

    /// Whether no files are listed.
    pub fn is_empty(&self) -> bool {
        self.files.is_empty()
    }

    /// Sum of listed file sizes.
    pub fn total_size(&self) -> u64 {
        self.files.values().map(|f| f.size).sum()
    }
}


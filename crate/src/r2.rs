        #[test]
        fn offline_mode_and_cached_list_fallback() {
            let fx = Fixture::new("offline");
            // Nothing cached yet: offline is an error, not a silent empty corpus.
            let err = fx.pull(fx.options().mode(PullMode::Offline)).unwrap_err();
            assert!(matches!(err, Error::NetworkUnavailable { .. }), "{err}");

            fx.put_object("a.bin", b"a");
            fx.put_list(&list_with(&[("a.bin", b"a", false)], None));
            fx.pull(fx.options()).unwrap();

            // Offline with a complete cache succeeds without any fetch.
            fx.reset_log();
            let c = fx.pull(fx.options().mode(PullMode::Offline)).unwrap();
            assert_eq!(fx.fetched_total(), 0);
            assert_eq!(std::fs::read(c.file_path("a.bin")).unwrap(), b"a");

            // Offline with a missing file fails loudly.
            std::fs::remove_file(c.file_path("a.bin")).unwrap();
            let err = fx.pull(fx.options().mode(PullMode::Offline)).unwrap_err();
            assert!(matches!(err, Error::PathNotFound { .. }), "{err}");

            // Network gone (remote wiped) but a cached list exists: Auto falls
            // back to the cached list and repairs from... nothing, so it fails
            // on the missing file; with the file present it succeeds.
            std::fs::remove_dir_all(&fx.remote).unwrap();
            let err = fx.pull(fx.options()).unwrap_err();
            assert!(matches!(err, Error::DownloadFailed { .. }), "{err}");
            std::fs::write(c.file_path("a.bin"), b"a").unwrap();
            let c2 = fx.pull(fx.options()).unwrap();
            assert_eq!(c2.list().len(), 1);
            fx.cleanup();
        }


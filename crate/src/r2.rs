/// Strip leading `/`, require a non-empty, `..`-free path, add a trailing `/`.
pub(crate) fn normalize_prefix(prefix: &str) -> Result<String, Error> {
    let trimmed = prefix.trim_matches('/');
    if trimmed.is_empty() {
        return Err(Error::ListParse("prefix must not be empty".to_string()));
    }
    validate_rel_path(trimmed)?;
    Ok(format!("{trimmed}/"))
}

/// Reject absolute paths, `..`, empty components, and backslashes.
fn validate_rel_path(rel: &str) -> Result<(), Error> {
    let bad = rel.is_empty()
        || rel.starts_with('/')
        || rel.contains('\\')
        || rel.contains('\0')
        || rel
            .split('/')
            .any(|c| c.is_empty() || c == "." || c == "..");
    if bad {
        Err(Error::ListParse(format!("unsafe path in .list: '{rel}'")))
    } else {
        Ok(())
    }
}

/// `<base>/<prefix-without-trailing-slash>.list`
pub(crate) fn list_url(base_url: &str, prefix: &str) -> String {
    format!(
        "{}/{}.list",
        base_url.trim_end_matches('/'),
        prefix.trim_end_matches('/')
    )
}

/// `<base>/<prefix><rel>`
pub(crate) fn file_url(base_url: &str, prefix: &str, rel: &str) -> String {
    format!("{}/{prefix}{rel}", base_url.trim_end_matches('/'))
}

/// `<base>/<key>`
pub(crate) fn bundle_url(base_url: &str, key: &str) -> String {
    format!(
        "{}/{}",
        base_url.trim_end_matches('/'),
        key.trim_start_matches('/')
    )
}

/// `{cache_base}/codec-corpus/r2/{host}/{prefix components...}`
pub(crate) fn cache_dir_for(cache_base: &Path, base_url: &str, prefix: &str) -> PathBuf {
    let host = base_url
        .split("://")
        .nth(1)
        .unwrap_or(base_url)
        .trim_end_matches('/');
    let host: String = host
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' || c == '.' {
                c
            } else {
                '_'
            }
        })
        .collect();
    let mut dir = cache_base.join("codec-corpus").join("r2").join(host);
    for comp in prefix.trim_end_matches('/').split('/') {
        dir.push(comp);
    }
    dir
}

fn join_rel(dir: &Path, rel: &str) -> PathBuf {
    let mut p = dir.to_path_buf();
    for comp in rel.split('/') {
        p.push(comp);
    }
    p
}

fn default_cache_base() -> Result<PathBuf, Error> {
    if let Ok(val) = std::env::var("CODEC_CORPUS_CACHE") {
        return Ok(PathBuf::from(val));
    }
    dirs::cache_dir().ok_or(Error::NoCacheDir)
}

fn temp_path(dir: &Path, tag: &str) -> PathBuf {
    // pid + a process-wide counter: unique across concurrent worker threads
    // (a timestamp alone can collide within the clock's resolution).
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let pid = std::process::id();
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    dir.join(format!(".tmp-{tag}-{pid}-{n}"))
}

/// Coarse RFC 3339 UTC timestamp without a date library (days since epoch
/// → civil date via the standard algorithm).
fn rfc3339_now() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();
    let days = (secs / 86_400) as i64;
    let rem = secs % 86_400;
    let (h, m, s) = (rem / 3600, (rem % 3600) / 60, rem % 60);
    // Howard Hinnant's civil_from_days.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let mo = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if mo <= 2 { y + 1 } else { y };
    format!("{y:04}-{mo:02}-{d:02}T{h:02}:{m:02}:{s:02}Z")
}

/// Hold the prefix dir's `.lock` for the duration of `f` (native only).
fn with_dir_lock<T>(dir: &Path, f: impl FnOnce() -> Result<T, Error>) -> Result<T, Error> {
    #[cfg(not(target_arch = "wasm32"))]
    {
        let lock_file = std::fs::File::create(dir.join(".lock"))?;
        let mut lock = fd_lock::RwLock::new(lock_file);
        let _guard = lock.write()?;
        f()
    }
    #[cfg(target_arch = "wasm32")]
    {
        // Single-process runtime: nothing to lock against.
        let _ = dir;
        f()
    }
}


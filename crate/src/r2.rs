/// A pulled corpus prefix: a local directory that mirrors
/// `<base_url>/<prefix>` and can be walked with `std::fs`.
///
/// ```no_run
/// let corpus = codec_corpus::R2Corpus::pull(
///     codec_corpus::DEFAULT_R2_BASE_URL,
///     "fuzz/zentiff/fuzz_decode/",
/// )?;
/// for entry in std::fs::read_dir(corpus.path())? {
///     let bytes = std::fs::read(entry?.path())?;
///     // feed your decoder...
/// }
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
#[derive(Debug)]
pub struct R2Corpus {
    base_url: String,
    prefix: String,
    dir: PathBuf,
    list: ListIndex,
}

/// Something that fetches `url` into the file at `dest`. The real one is the
/// crate's `curl`/`wget`/`powershell` chain; tests inject a local copier. It
/// is called from several threads at once when fetching individual objects.
pub(crate) type Fetcher<'a> = &'a (dyn Fn(&str, &Path) -> Result<(), Error> + Sync);

impl R2Corpus {
    /// Pull `prefix` from `base_url` (anonymous HTTP GETs) into the cache and
    /// return a handle to the local directory. See the module docs for the
    /// algorithm.
    pub fn pull(base_url: &str, prefix: &str) -> Result<Self, Error> {
        Self::pull_with_options(base_url, prefix, PullOptions::default())
    }

    /// [`R2Corpus::pull`] with explicit [`PullOptions`].
    pub fn pull_with_options(
        base_url: &str,
        prefix: &str,
        options: PullOptions,
    ) -> Result<Self, Error> {
        #[cfg(target_arch = "wasm32")]
        {
            if options.mode != PullMode::Offline {
                return Err(Error::DownloadUnsupported {
                    dataset: prefix.to_string(),
                });
            }
            Self::pull_with_fetcher(base_url, prefix, options, &|_url, _dest| {
                Err(Error::DownloadUnsupported {
                    dataset: prefix.to_string(),
                })
            })
        }
        #[cfg(not(target_arch = "wasm32"))]
        {
            Self::pull_with_fetcher(base_url, prefix, options, &crate::download::download_file)
        }
    }

    /// Local directory mirroring the remote prefix.
    pub fn path(&self) -> &Path {
        &self.dir
    }

    /// The `.list` this directory was synced against. When the prefix has
    /// child prefixes (and the pull was recursive) this is the merged view:
    /// the node's own files plus every child's files keyed `child/rel`, with
    /// the node's own `bundle` and `children`.
    pub fn list(&self) -> &ListIndex {
        &self.list
    }

    /// The normalized prefix (trailing `/`).
    pub fn prefix(&self) -> &str {
        &self.prefix
    }

    /// The base URL this corpus was pulled from.
    pub fn base_url(&self) -> &str {
        &self.base_url
    }

    /// Local path of one listed file (whether or not it exists yet).
    pub fn file_path(&self, rel: &str) -> PathBuf {
        join_rel(&self.dir, rel)
    }

    /// Iterate `(relative path, entry)` in stable (sorted) order.
    pub fn files(&self) -> impl Iterator<Item = (&str, &FileEntry)> {
        self.list.files.iter().map(|(k, v)| (k.as_str(), v))
    }

    pub(crate) fn pull_with_fetcher(
        base_url: &str,
        prefix: &str,
        options: PullOptions,
        fetch: Fetcher<'_>,
    ) -> Result<Self, Error> {
        let base_url = base_url.trim_end_matches('/').to_string();
        let prefix = normalize_prefix(prefix)?;
        let cache_base = match &options.cache_root {
            Some(r) => r.clone(),
            None => default_cache_base()?,
        };
        let dir = cache_dir_for(&cache_base, &base_url, &prefix);
        std::fs::create_dir_all(&dir)?;

        let list = with_dir_lock(&dir, || {
            sync_prefix(&base_url, &prefix, &dir, &options, fetch)
        })?;

        Ok(Self {
            base_url,
            prefix,
            dir,
            list,
        })
    }
}

/// The locked body of a pull: returns the list the directory now matches.
fn sync_prefix(
    base_url: &str,
    prefix: &str,
    dir: &Path,
    options: &PullOptions,
    fetch: Fetcher<'_>,
) -> Result<ListIndex, Error> {
    let cached_list_path = dir.join(CACHED_LIST_NAME);

    // 1. The list.
    let mut list = if options.mode == PullMode::Offline {
        let text =
            std::fs::read_to_string(&cached_list_path).map_err(|_| Error::NetworkUnavailable {
                dataset: prefix.to_string(),
            })?;
        ListIndex::parse(&text)?
    } else {
        let tmp = temp_path(dir, "list");
        match fetch(&list_url(base_url, prefix), &tmp) {
            Ok(()) => {
                let text = std::fs::read_to_string(&tmp)?;
                let _ = std::fs::remove_file(&tmp);
                ListIndex::parse(&text)?
            }
            Err(_) => {
                let _ = std::fs::remove_file(&tmp);
                // Fall back to the last successful pull, if any.
                let Ok(text) = std::fs::read_to_string(&cached_list_path) else {
                    return Err(Error::NetworkUnavailable {
                        dataset: prefix.to_string(),
                    });
                };
                eprintln!(
                    "codec-corpus: warning: could not fetch {}; using the cached list for '{prefix}'",
                    list_url(base_url, prefix)
                );
                ListIndex::parse(&text)?
            }
        }
    };

    // 2. Diff.
    let mut missing: Vec<&str> = Vec::new();
    for (rel, entry) in &list.files {
        if !local_matches(&join_rel(dir, rel), entry) {
            missing.push(rel);
        }
    }

    if options.mode == PullMode::Offline {
        if let Some(first) = missing.first() {
            return Err(Error::PathNotFound {
                path: format!("{prefix}{first} (offline; {} files missing)", missing.len()),
            });
        }
        if options.recursive {
            sync_children(base_url, prefix, dir, &mut list, options, fetch)?;
        }
        return Ok(list);
    }

    // 3. Bundle.
    if let Some(bundle) = &list.bundle {
        let missing_bundled = missing
            .iter()
            .filter(|rel| list.files[**rel].in_bundle)
            .count();
        let use_bundle = match options.mode {
            PullMode::ForceBundle => true,
            PullMode::NoBundle | PullMode::Offline => false,
            PullMode::Auto => {
                missing_bundled > 0
                    && (missing_bundled as f32 / bundle.file_count.max(1) as f32)
                        >= options.bundle_threshold
            }
        };
        if use_bundle {
            fetch_bundle(base_url, dir, &list, bundle, fetch)?;
            missing.retain(|rel| !local_matches(&join_rel(dir, rel), &list.files[*rel]));
        }
    }

    // 4. Individual objects.
    fetch_objects(
        base_url,
        prefix,
        dir,
        &list,
        &missing,
        options.parallelism,
        fetch,
    )?;

    // 5. Prune + record the list we now match.
    if options.prune {
        prune_unlisted(dir, dir, &list)?;
    }
    let tmp = temp_path(dir, "list");
    std::fs::write(&tmp, list.to_json())?;
    std::fs::rename(&tmp, &cached_list_path)?;

    // 6. Children.
    if options.recursive {
        sync_children(base_url, prefix, dir, &mut list, options, fetch)?;
    }
    Ok(list)
}

/// Pull every child prefix named in `list` into `dir/<child>/` and fold its
/// files into `list` as `child/rel` (the merged view).
fn sync_children(
    base_url: &str,
    prefix: &str,
    dir: &Path,
    list: &mut ListIndex,
    options: &PullOptions,
    fetch: Fetcher<'_>,
) -> Result<(), Error> {
    let children = list.children.clone();
    for child in &children {
        let child_prefix = format!("{prefix}{child}/");
        let child_dir = dir.join(child);
        std::fs::create_dir_all(&child_dir)?;
        let child_list = with_dir_lock(&child_dir, || {
            sync_prefix(base_url, &child_prefix, &child_dir, options, fetch)
        })?;
        for (rel, entry) in child_list.files {
            list.files.insert(format!("{child}/{rel}"), entry);
        }
    }
    Ok(())
}

/// Fetch `missing` objects into place, `parallelism` at a time. The first
/// failure stops the remaining work and is returned; files already placed
/// stay (they were verified), temp files are cleaned up.
fn fetch_objects(
    base_url: &str,
    prefix: &str,
    dir: &Path,
    list: &ListIndex,
    missing: &[&str],
    parallelism: usize,
    fetch: Fetcher<'_>,
) -> Result<(), Error> {
    if missing.is_empty() {
        return Ok(());
    }
    let fetch_one = |rel: &str| -> Result<(), Error> {
        let entry = &list.files[rel];
        let dest = join_rel(dir, rel);
        if let Some(parent) = dest.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let tmp = temp_path(dir, "obj");
        let url = file_url(base_url, prefix, rel);
        if let Err(e) = fetch(&url, &tmp) {
            let _ = std::fs::remove_file(&tmp);
            return Err(match e {
                Error::Io(io) => Error::Io(io),
                _ => Error::DownloadFailed {
                    url,
                    reason: "all download methods failed (curl, wget, powershell)".to_string(),
                },
            });
        }
        place_verified(&tmp, &dest, rel, entry)
    };

    // wasm32 has no threads to spawn; a single worker is also the
    // deterministic path tests use to pin error ordering.
    let workers = if cfg!(target_arch = "wasm32") {
        1
    } else {
        parallelism.clamp(1, missing.len())
    };
    if workers == 1 {
        for rel in missing {
            fetch_one(rel)?;
        }
        return Ok(());
    }

    let next = Mutex::new(0usize);
    let failure: Mutex<Option<Error>> = Mutex::new(None);
    std::thread::scope(|scope| {
        for _ in 0..workers {
            scope.spawn(|| {
                loop {
                    let i = {
                        let mut n = next.lock().unwrap_or_else(|p| p.into_inner());
                        let i = *n;
                        *n += 1;
                        i
                    };
                    if i >= missing.len() {
                        return;
                    }
                    if failure.lock().unwrap_or_else(|p| p.into_inner()).is_some() {
                        return;
                    }
                    if let Err(e) = fetch_one(missing[i]) {
                        let mut f = failure.lock().unwrap_or_else(|p| p.into_inner());
                        if f.is_none() {
                            *f = Some(e);
                        }
                        return;
                    }
                }
            });
        }
    });
    match failure.into_inner().unwrap_or_else(|p| p.into_inner()) {
        Some(e) => Err(e),
        None => Ok(()),
    }
}

/// Download, verify, and extract the bundle, moving every listed
/// `in_bundle` member whose hash checks out into place.
fn fetch_bundle(
    base_url: &str,
    dir: &Path,
    list: &ListIndex,
    bundle: &BundleInfo,
    fetch: Fetcher<'_>,
) -> Result<(), Error> {
    let url = bundle_url(base_url, &bundle.key);
    let archive = temp_path(dir, "bundle");
    if let Err(e) = fetch(&url, &archive) {
        let _ = std::fs::remove_file(&archive);
        return Err(match e {
            Error::Io(io) => Error::Io(io),
            _ => Error::DownloadFailed {
                url,
                reason: "all download methods failed (curl, wget, powershell)".to_string(),
            },
        });
    }
    let actual = sha256::sha256_file(&archive)?;
    if actual != bundle.sha256 {
        let _ = std::fs::remove_file(&archive);
        return Err(Error::ChecksumMismatch {
            path: bundle.key.clone(),
            expected: bundle.sha256.clone(),
            actual,
        });
    }

    let extract = temp_path(dir, "extract");
    std::fs::create_dir_all(&extract)?;
    let extracted = extract_archive(&archive, &bundle.key, &extract);
    let _ = std::fs::remove_file(&archive);
    if let Err(e) = extracted {
        let _ = std::fs::remove_dir_all(&extract);
        return Err(e);
    }

    for (rel, entry) in &list.files {
        if !entry.in_bundle {
            continue;
        }
        let src = join_rel(&extract, rel);
        if !src.is_file() {
            continue; // stale list vs bundle: the delta path picks it up
        }
        let dest = join_rel(dir, rel);
        if let Some(parent) = dest.parent() {
            std::fs::create_dir_all(parent)?;
        }
        // A member whose hash disagrees with the list is simply not placed;
        // it is re-fetched individually (and verified) afterwards.
        if sha256::sha256_file(&src)? == entry.sha256 {
            move_file(&src, &dest)?;
        }
    }
    let _ = std::fs::remove_dir_all(&extract);
    Ok(())
}

/// Extract `archive` (format chosen by the extension of `key`) into `dest`
/// with the system `tar`, falling back to a standalone `zstd` for `.tar.zst`
/// when `tar` lacks built-in zstd support.
fn extract_archive(archive: &Path, key: &str, dest: &Path) -> Result<(), Error> {
    use std::process::{Command, Stdio};
    let run_tar = |args: &[&str], input: &Path| -> bool {
        Command::new("tar")
            .args(args)
            .arg(input)
            .arg("-C")
            .arg(dest)
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
    };
    let ok = if key.ends_with(".tar.zst") || key.ends_with(".tzst") {
        run_tar(&["--zstd", "-xf"], archive) || {
            // Decompress to a sibling .tar with the zstd binary, then plain tar.
            let plain = archive.with_extension("tar");
            let decompressed = Command::new("zstd")
                .args(["-d", "-q", "-f", "-o"])
                .arg(&plain)
                .arg(archive)
                .stdout(Stdio::null())
                .stderr(Stdio::null())
                .status()
                .map(|s| s.success())
                .unwrap_or(false);
            let r = decompressed && run_tar(&["-xf"], &plain);
            let _ = std::fs::remove_file(&plain);
            r
        }
    } else if key.ends_with(".tar.gz") || key.ends_with(".tgz") {
        run_tar(&["-xzf"], archive)
    } else if key.ends_with(".tar") {
        run_tar(&["-xf"], archive)
    } else {
        return Err(Error::ListParse(format!(
            "bundle key '{key}' has an unsupported archive extension (want .tar, .tar.gz, .tar.zst)"
        )));
    };
    if ok {
        Ok(())
    } else {
        Err(Error::DownloadFailed {
            url: key.to_string(),
            reason: "bundle extraction failed (is `tar` — and `zstd` for .tar.zst — installed?)"
                .to_string(),
        })
    }
}

/// Verify `tmp` against `entry`, then move it to `dest`. On mismatch the
/// temp file is deleted and nothing is placed.
fn place_verified(tmp: &Path, dest: &Path, rel: &str, entry: &FileEntry) -> Result<(), Error> {
    let size = std::fs::metadata(tmp)?.len();
    let actual = sha256::sha256_file(tmp)?;
    if size != entry.size || actual != entry.sha256 {
        let _ = std::fs::remove_file(tmp);
        return Err(Error::ChecksumMismatch {
            path: rel.to_string(),
            expected: entry.sha256.clone(),
            actual,
        });
    }
    move_file(tmp, dest)
}

fn move_file(src: &Path, dest: &Path) -> Result<(), Error> {
    if std::fs::rename(src, dest).is_err() {
        std::fs::copy(src, dest)?;
        let _ = std::fs::remove_file(src);
    }
    Ok(())
}

/// Does the local file exist with the listed size and SHA-256?
fn local_matches(path: &Path, entry: &FileEntry) -> bool {
    let Ok(meta) = std::fs::metadata(path) else {
        return false;
    };
    if !meta.is_file() || meta.len() != entry.size {
        return false;
    }
    matches!(sha256::sha256_file(path), Ok(h) if h == entry.sha256)
}

/// Remove regular files under `dir` that are not listed (hidden names at the
/// root — `.list.json`, `.lock`, `.tmp-*` — are the crate's own and stay).
/// Child-prefix directories are owned by their own sync and are skipped.
fn prune_unlisted(root: &Path, dir: &Path, list: &ListIndex) -> Result<(), Error> {
    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        let name = entry.file_name();
        if dir == root && name.to_string_lossy().starts_with('.') {
            continue;
        }
        if dir == root && path.is_dir() && list.children.iter().any(|c| **c == *name) {
            continue;
        }
        if path.is_dir() {
            prune_unlisted(root, &path, list)?;
            // Drop directories that ended up empty.
            if std::fs::read_dir(&path)?.next().is_none() {
                let _ = std::fs::remove_dir(&path);
            }
        } else {
            let rel = path
                .strip_prefix(root)
                .map_err(|e| std::io::Error::other(e.to_string()))?
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            if !list.files.contains_key(&rel) {
                std::fs::remove_file(&path)?;
            }
        }
    }
    Ok(())
}


/// How a pull decides between the bundle and individual objects.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[non_exhaustive]
pub enum PullMode {
    /// Fetch the bundle when at least `bundle_threshold` of its files are
    /// missing locally, individual objects otherwise.
    #[default]
    Auto,
    /// Always fetch the bundle if the list has one (cold-start fast path).
    ForceBundle,
    /// Never fetch the bundle; individual objects only.
    NoBundle,
    /// Do no network I/O at all: open the cache left by a previous pull,
    /// verifying every listed file is present with the right SHA-256. Works
    /// on `wasm32`.
    Offline,
}

/// Tunables for [`R2Corpus::pull_with_options`]. Build with
/// [`PullOptions::default`] and the setters.
#[derive(Debug, Clone)]
pub struct PullOptions {
    mode: PullMode,
    cache_root: Option<PathBuf>,
    bundle_threshold: f32,
    prune: bool,
    parallelism: usize,
    recursive: bool,
}

/// Default number of concurrent individual-object fetches.
pub const DEFAULT_PARALLELISM: usize = 8;

impl Default for PullOptions {
    fn default() -> Self {
        Self {
            mode: PullMode::Auto,
            cache_root: None,
            bundle_threshold: 0.4,
            prune: true,
            parallelism: DEFAULT_PARALLELISM,
            recursive: true,
        }
    }
}

impl PullOptions {
    /// Bundle-vs-individual policy (default [`PullMode::Auto`]).
    pub fn mode(mut self, mode: PullMode) -> Self {
        self.mode = mode;
        self
    }

    /// Explicit cache root (default: `CODEC_CORPUS_CACHE` env var, else the
    /// platform cache dir). Files land under `{root}/codec-corpus/r2/…`.
    pub fn cache_root(mut self, root: impl Into<PathBuf>) -> Self {
        self.cache_root = Some(root.into());
        self
    }

    /// In [`PullMode::Auto`], the fraction (`0.0..=1.0`) of bundled files that
    /// must be missing before the bundle is fetched instead of individual
    /// objects. Default `0.4`.
    pub fn bundle_threshold(mut self, fraction: f32) -> Self {
        self.bundle_threshold = fraction.clamp(0.0, 1.0);
        self
    }

    /// Whether to delete cached files that are no longer in the `.list`
    /// (default `true`, so the directory mirrors the remote prefix).
    pub fn prune(mut self, prune: bool) -> Self {
        self.prune = prune;
        self
    }

    /// How many individual objects to fetch concurrently (default
    /// [`DEFAULT_PARALLELISM`]; `0` and `1` both mean sequential). Each fetch
    /// is its own `curl`/`wget` process, so this is also the number of
    /// concurrent connections.
    pub fn parallelism(mut self, n: usize) -> Self {
        self.parallelism = n.max(1);
        self
    }

    /// Whether to pull child prefixes named in the `.list` (default `true`).
    /// With `false` only the node's own files are synced.
    pub fn recursive(mut self, recursive: bool) -> Self {
        self.recursive = recursive;
        self
    }
}

